import { describe, expect, it } from 'vitest';
import { createPrivateKey } from 'node:crypto';
import { generateDer, generatePem, parsePem, parsePkDer, parseSkDer } from '../src/index.js';
import { defined, generateRawKeyPair } from './helpers.js';

const { sk, pk } = generateRawKeyPair('prime256v1');
const { privateKey, publicKey } = generatePem('prime256v1', { sk, pk });
const PRIVATE = defined(privateKey);
const PUBLIC = defined(publicKey);

const expectPrivateKey = (pem: string): void => {
    expect(parsePem(pem)).toEqual({ curveName: 'prime256v1', privateKey: sk, publicKey: pk });
};

describe('real-world PEM formatting', () => {
    it('accepts a UTF-8 BOM', () => {
        expect(parsePem(`\uFEFF${PUBLIC}`).publicKey).toEqual(pk);
    });

    it('accepts trailing whitespace after the labels', () => {
        const padded = PRIVATE.split('\n')
            .map((line) => (line.startsWith('-----') ? `${line}  \t` : line))
            .join('\n');
        expectPrivateKey(padded);
    });

    it('accepts an indented block', () => {
        const indented = PRIVATE.split('\n')
            .map((line) => `  ${line}`)
            .join('\n');
        expectPrivateKey(indented);
        expect(parsePem(`\t${PUBLIC}`).publicKey).toEqual(pk);
    });

    it('accepts blank lines inside the body', () => {
        const spaced = PRIVATE.replace('\n', '\n\n');
        expectPrivateKey(spaced);
    });

    it('accepts mixed CRLF and LF line endings', () => {
        const lines = PRIVATE.split('\n');
        const mixed = lines
            .map((line, index) => (index % 2 === 0 ? `${line}\r\n` : `${line}\n`))
            .join('');
        expectPrivateKey(mixed.replace('\r\n\n', '\r\n'));
    });

    it('accepts a body wrapped at unusual widths', () => {
        const [begin, ...rest] = PRIVATE.split('\n');
        const end = rest.pop() as string;
        const body = rest.join('');
        const rewrapped = [
            begin,
            ...[...body]
                .join('')
                .match(/.{1,20}/g)!
                .join('\n'),
            end,
        ].join('\n');
        expectPrivateKey(rewrapped);
    });
});

describe('PEM as other tools write it', () => {
    const EC_PARAMETERS =
        '-----BEGIN EC PARAMETERS-----\nBggqhkjOPQMBBw==\n-----END EC PARAMETERS-----';

    it('reads `openssl ecparam -genkey` output, curve block first', () => {
        expectPrivateKey(`${EC_PARAMETERS}\n${PRIVATE}\n`);
    });

    it('ignores explanatory text around the block (RFC 7468 section 2)', () => {
        expectPrivateKey(
            `Bag Attributes\n    localKeyID: 01 02 03\nKey Attributes: <No Attributes>\n${PRIVATE}\n`
        );
        expect(parsePem(`${PUBLIC}\n# generated by openssl`).publicKey).toEqual(pk);
    });

    it('decrypts the key block, not the curve block in front of it', () => {
        const encrypted = createPrivateKey(PRIVATE)
            .export({ format: 'pem', type: 'pkcs8', cipher: 'aes-256-cbc', passphrase: 'pw' })
            .toString();
        expect(parsePem(`${EC_PARAMETERS}\n${encrypted}`, { passphrase: 'pw' })).toEqual({
            curveName: 'prime256v1',
            privateKey: sk,
            publicKey: pk,
        });
    });
});

describe('DER of the wrong kind', () => {
    it('tells a public key passed as a private key apart from an encrypted one', () => {
        const spki = defined(generateDer('prime256v1', { pk }).publicKey);
        expect(() => parseSkDer(spki)).toThrow(
            'Expected a private key, got a SubjectPublicKeyInfo: use parsePkDer'
        );
    });

    it('reports a structure that is neither as an invalid private key', () => {
        // SEQUENCE { SEQUENCE {}, INTEGER 0 }
        const neither = Buffer.from('30053000020100', 'hex');
        expect(() => parseSkDer(neither)).toThrow('Invalid DER encoding of ECPrivateKey');
    });
});

describe('PEM inputs it refuses', () => {
    it('refuses two key blocks in one string rather than guess', () => {
        expect(() => parsePem(`${PRIVATE}\n${PUBLIC}`)).toThrow(
            'PEM content holds 2 blocks (EC PRIVATE KEY, PUBLIC KEY); expected one key'
        );
    });

    it('names an EC PARAMETERS block that comes without a key', () => {
        const parameters =
            '-----BEGIN EC PARAMETERS-----\nBggqhkjOPQMBBw==\n-----END EC PARAMETERS-----';
        expect(() => parsePem(parameters)).toThrow('Unsupported PEM label "EC PARAMETERS"');
    });

    it('refuses a lowercase label', () => {
        expect(() => parsePem(PUBLIC.replace(/PUBLIC KEY/g, 'public key'))).toThrow(
            'Invalid or unsupported PEM content'
        );
    });

    it('refuses a certificate and other labels by name', () => {
        const body = PRIVATE.split('\n').slice(1, -1).join('\n');
        expect(() =>
            parsePem(`-----BEGIN CERTIFICATE-----\n${body}\n-----END CERTIFICATE-----`)
        ).toThrow('Unsupported PEM label "CERTIFICATE"');
        expect(() =>
            parsePem(
                `-----BEGIN ENCRYPTED PRIVATE KEY-----\n${body}\n-----END ENCRYPTED PRIVATE KEY-----`
            )
        ).toThrow('Encrypted PEM requires a passphrase');
    });

    it('refuses non-ASCII content', () => {
        expect(() => parsePem(PUBLIC.replace('KEY', 'KE\u00DD'))).toThrow();
    });

    it('refuses a block whose base64 body is empty', () => {
        expect(() => parsePem('-----BEGIN PUBLIC KEY-----\n\n-----END PUBLIC KEY-----')).toThrow();
        expect(() =>
            parsePem('-----BEGIN PUBLIC KEY-----\n   \n-----END PUBLIC KEY-----')
        ).toThrow();
    });

    it('refuses the block with a missing newline after the label', () => {
        expect(() => parsePem('-----BEGIN PUBLIC KEY-----AAAA\n-----END PUBLIC KEY-----')).toThrow(
            'Invalid or unsupported PEM content'
        );
    });

    it('rejects a public key whose BIT STRING has unused bits', () => {
        const der = Buffer.from(PUBLIC.split('\n').slice(1, -1).join(''), 'base64');
        const unusedBitsAt = der.length - 66;
        expect(der[unusedBitsAt]).toBe(0);
        der[unusedBitsAt] = 3;
        expect(() => parsePkDer(der)).toThrow('Invalid DER encoding of SubjectPublicKeyInfo');
    });
});
