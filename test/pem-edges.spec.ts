import { describe, expect, it } from 'vitest';
import { generatePem, parsePem } from '../src/index.js';
import { defined, generateRawKeyPair } from './helpers.js';

const { sk, pk } = generateRawKeyPair('prime256v1');
const { privateKey, publicKey } = generatePem('prime256v1', { sk, pk });
const PRIVATE = defined(privateKey);
const PUBLIC = defined(publicKey);

const expectPrivateKey = (pem: string): void => {
  expect(parsePem(pem)).toEqual({ curveName: 'prime256v1', privateKey: sk, publicKey: pk });
};

describe('real-world PEM formatting', () => {
  it('accepts a UTF-8 BOM', () => {
    expect(parsePem(`\uFEFF${PUBLIC}`).publicKey).toEqual(pk);
  });

  it('accepts trailing whitespace after the labels', () => {
    const padded = PRIVATE.split('\n')
      .map((line) => (line.startsWith('-----') ? `${line}  \t` : line))
      .join('\n');
    expectPrivateKey(padded);
  });

  it('accepts an indented block', () => {
    const indented = PRIVATE.split('\n')
      .map((line) => `  ${line}`)
      .join('\n');
    expectPrivateKey(indented);
    expect(parsePem(`\t${PUBLIC}`).publicKey).toEqual(pk);
  });

  it('accepts blank lines inside the body', () => {
    const spaced = PRIVATE.replace('\n', '\n\n');
    expectPrivateKey(spaced);
  });

  it('accepts mixed CRLF and LF line endings', () => {
    const lines = PRIVATE.split('\n');
    const mixed = lines
      .map((line, index) => (index % 2 === 0 ? `${line}\r\n` : `${line}\n`))
      .join('');
    expectPrivateKey(mixed.replace('\r\n\n', '\r\n'));
  });

  it('accepts a body wrapped at unusual widths', () => {
    const [begin, ...rest] = PRIVATE.split('\n');
    const end = rest.pop() as string;
    const body = rest.join('');
    const rewrapped = [
      begin,
      ...[...body]
        .join('')
        .match(/.{1,20}/g)!
        .join('\n'),
      end,
    ].join('\n');
    expectPrivateKey(rewrapped);
  });
});

describe('PEM inputs it refuses', () => {
  it('refuses two blocks in one string', () => {
    expect(() => parsePem(`${PRIVATE}\n${PUBLIC}`)).toThrow('Invalid or unsupported PEM content');
  });

  it('refuses a lowercase label', () => {
    expect(() => parsePem(PUBLIC.replace(/PUBLIC KEY/g, 'public key'))).toThrow(
      'Invalid or unsupported PEM content'
    );
  });

  it('refuses a certificate and other labels by name', () => {
    const body = PRIVATE.split('\n').slice(1, -1).join('\n');
    expect(() =>
      parsePem(`-----BEGIN CERTIFICATE-----\n${body}\n-----END CERTIFICATE-----`)
    ).toThrow('Unsupported PEM label "CERTIFICATE"');
    expect(() =>
      parsePem(
        `-----BEGIN ENCRYPTED PRIVATE KEY-----\n${body}\n-----END ENCRYPTED PRIVATE KEY-----`
      )
    ).toThrow('Unsupported PEM label "ENCRYPTED PRIVATE KEY"');
  });

  it('refuses non-ASCII content', () => {
    expect(() => parsePem(PUBLIC.replace('KEY', 'KE\u00DD'))).toThrow();
  });

  it('refuses a block whose base64 body is empty', () => {
    expect(() => parsePem('-----BEGIN PUBLIC KEY-----\n\n-----END PUBLIC KEY-----')).toThrow();
    expect(() => parsePem('-----BEGIN PUBLIC KEY-----\n   \n-----END PUBLIC KEY-----')).toThrow();
  });

  it('refuses the block with a missing newline after the label', () => {
    expect(() => parsePem('-----BEGIN PUBLIC KEY-----AAAA\n-----END PUBLIC KEY-----')).toThrow(
      'Invalid or unsupported PEM content'
    );
  });

  it('refuses a trailing comment after the block', () => {
    expect(() => parsePem(`${PUBLIC}\n# generated by openssl`)).toThrow();
  });
});
